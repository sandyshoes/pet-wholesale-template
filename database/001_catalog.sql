CREATE TABLE IF NOT EXISTS products (
 id VARCHAR(64) PRIMARY KEY, name VARCHAR(255) NOT NULL,
 category VARCHAR(100) NOT NULL DEFAULT '', price DECIMAL(10,2) NOT NULL DEFAULT 0,
 description TEXT, images LONGTEXT, colors LONGTEXT, sizes LONGTEXT, specs LONGTEXT,
 featured TINYINT NOT NULL DEFAULT 0, status VARCHAR(20) NOT NULL DEFAULT 'off',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS admin_users (
 id INT AUTO_INCREMENT PRIMARY KEY, username VARCHAR(50) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, role VARCHAR(20) DEFAULT 'admin',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS categories (
 name VARCHAR(100) PRIMARY KEY
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
INSERT IGNORE INTO categories(name) SELECT DISTINCT category FROM products WHERE category <> '';
CREATE TABLE IF NOT EXISTS app_login_limits (
 bucket CHAR(64) PRIMARY KEY, failures INT NOT NULL DEFAULT 0, started_at BIGINT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
